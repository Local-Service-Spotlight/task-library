const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const os = require('node:os');
// Usage: node scripts/check_training_ui.cjs <training.html URL> [output directory]
// Requires an already-installed Playwright and Chromium; never installs dependencies.
// The /task-library/ route is simulated on this same origin by serving the provided source directory.
const target = new URL(process.argv[2] || 'http://127.0.0.1:8769/training.html');
if (!['http:', 'https:'].includes(target.protocol)) throw new Error('Use an HTTP(S) training page URL.');
const qa = process.argv[3] ? path.resolve(process.argv[3]) : fs.mkdtempSync(path.join(os.tmpdir(), 'task-library-ui-'));
const preview = new URL('/task-library/training.html', target.origin).href;
const sourceBase = new URL('./', target).pathname;
const results = {checks: [], screenshots: [], errors: [], outboundRequests: []};
function pass(name) { results.checks.push({name, result:'PASS'}); }
async function main() {
  fs.mkdirSync(qa, {recursive:true});
  const browser = await chromium.launch({headless:true, args:['--mute-audio']});
  try {
    const context = await browser.newContext({viewport:{width:1280,height:900},acceptDownloads:true});
    await context.addInitScript(() => {document.addEventListener('play', e => { if (e.target instanceof HTMLMediaElement) {e.target.muted=true;e.target.volume=0;e.target.pause();}}, true);});
    await context.route('**/*', route => {
      const url = new URL(route.request().url());
      if (url.origin !== target.origin) { results.outboundRequests.push(url.href); return route.abort(); }
      if (url.pathname.startsWith('/task-library/')) {
        url.pathname = sourceBase + url.pathname.slice('/task-library/'.length);
        return route.continue({url:url.href});
      }
      return route.continue();
    });
    const page = await context.newPage();
    page.on('pageerror', error => results.errors.push(error.message));
    const libraryEntry = await context.newPage();
    await libraryEntry.goto(new URL('/task-library/', target.origin).href, {waitUntil:'domcontentloaded'});
    const teachingEntry = libraryEntry.locator('a[href="training.html"]');
    assert.equal(await teachingEntry.getAttribute('target'), '_blank');
    assert((await teachingEntry.getAttribute('rel')).split(/\s+/).includes('noopener'));
    assert((await teachingEntry.getAttribute('aria-label')).includes('new tab'));
    const libraryEntryURL = libraryEntry.url();
    const entryPopupPromise = libraryEntry.waitForEvent('popup');
    await teachingEntry.click();
    const entryPopup = await entryPopupPromise;
    await entryPopup.locator('.path-choice').first().waitFor();
    assert.equal(libraryEntry.url(), libraryEntryURL);
    assert.equal(entryPopup.url(), preview);
    assert.equal(await entryPopup.evaluate(()=>window.opener), null);
    await entryPopup.close();
    await libraryEntry.close();
    pass('Dashboard teaching entry opens a separate protected-opener tab');
    await page.goto(preview+'?path=unknown', {waitUntil:'networkidle'});
    await page.locator('#route-message').waitFor({state:'visible'});
    assert.equal(await page.locator('#path-detail').isVisible(),false);
    pass('Unknown path explicitly rejected without substitute');
    const data = await page.evaluate(async()=> (await fetch('learning-paths.json')).json());
    assert.equal(await page.locator('.path-choice').count(),data.paths.length);
    for (const teachingPath of data.paths) {
      await page.goto(preview+'?path='+encodeURIComponent(teachingPath.id), {waitUntil:'networkidle'});
      assert.equal(await page.locator('#path-title').textContent(),teachingPath.title);
      assert.equal(await page.locator('.lesson-card').count(),teachingPath.lessonSlugs.length);
      assert.equal(new URL(await page.locator('#path-permalink').evaluate(e=>e.href)).searchParams.get('path'),teachingPath.id);
    }
    pass('Every generated teaching-path deep link resolves to its own path');
    await page.goto(preview, {waitUntil:'networkidle'});
    assert.equal(await page.getByRole('link',{name:'Browse tasks'}).evaluate(e=>e.href),new URL('/task-library/',target.origin).href);
    const fallbackPage=await context.newPage();
    const fallbackData=JSON.parse(JSON.stringify(data));
    const fallbackTask=fallbackData.tasks.find(t=>t.slug===data.paths[0].lessonSlugs[0]);
    delete fallbackTask.taskLibraryUrl;
    await fallbackPage.route('**/learning-paths.json',route=>route.fulfill({status:200,contentType:'application/json',body:JSON.stringify(fallbackData)}));
    await fallbackPage.goto(preview+'?path='+data.paths[0].id,{waitUntil:'networkidle'});
    assert.equal(await fallbackPage.locator('#lesson-list a').first().evaluate(e=>e.href),new URL('/task-library/',target.origin).href+'?task='+encodeURIComponent(fallbackTask.slug));
    await fallbackPage.close();
    pass('Deployed /task-library/ subpath browse and missing task-link fallback remain in library');
    await page.screenshot({path:path.join(qa,'training-desktop-1280x900.png')});
    results.screenshots.push('training-desktop-1280x900.png');
    await page.locator('.path-choice').first().click();
    assert.equal(await page.locator('#path-title').textContent(),data.paths[0].title);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'path-title');
    assert.equal(await page.locator('.lesson-card').count(),data.paths[0].lessonSlugs.length);
    assert((await page.locator('#framework-reference').textContent()).includes(data.framework.acceptanceStatus));
    assert((await page.locator('#framework-reference').textContent()).includes('does not mean these teaching paths are owner-approved'));
    await page.screenshot({path:path.join(qa,'training-desktop-path-full.png'),fullPage:true});
    results.screenshots.push('training-desktop-path-full.png');
    pass('Dynamic path selection and focus');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    assert.equal(await page.locator('audio,video').count(),0);
    pass('Desktop no horizontal overflow and no media players');
    await page.locator('#session-audience').fill('');
    assert.equal(await page.locator('#present-session').isDisabled(),true);
    assert.equal(await page.locator('#download-session').isDisabled(),true);
    await page.locator('#session-audience').fill('Workshop test group');
    await page.locator('#session-goal').fill('Bring back one checked result');
    await page.locator('#session-minutes').selectOption('60');
    assert.equal(await page.locator('#custom-warning').isVisible(),true);
    pass('Audience/result required and customization warning');
    const guide = page.locator('#lesson-list a').first();
    assert.equal(await guide.getAttribute('target'),'_blank');
    assert.equal(await guide.getAttribute('rel'),'noopener noreferrer');
    assert((await guide.getAttribute('aria-label')).includes('opens in a new tab'));
    const originalGuideURL = await guide.getAttribute('href');
    await guide.evaluate((element,url)=>{element.href=url;},preview+'?source-link-qa');
    const popupEvent=page.waitForEvent('popup');
    await guide.click();
    const popup=await popupEvent; await popup.waitForLoadState(); await popup.close();
    await guide.evaluate((element,url)=>{element.href=url;},originalGuideURL);
    assert.equal(await page.locator('#session-audience').inputValue(),'Workshop test group');
    assert.equal(await page.locator('#session-goal').inputValue(),'Bring back one checked result');
    pass('Source links open new tabs with current customized plan retained');
    const boxes=page.locator('.lesson-select input');
    for(let i=0;i<await boxes.count();i++) await boxes.nth(i).uncheck();
    assert.equal(await page.locator('#present-session').isDisabled(),true);
    await boxes.first().check();
    pass('Zero-selected lesson guard');
    await page.locator('.add-lesson summary').click();
    const extra=data.tasks.find(task=>!data.paths[0].lessonSlugs.includes(task.slug));
    await page.locator('#lesson-search').fill(extra.title);
    await page.locator('#lesson-option').selectOption(extra.slug);
    await page.locator('#add-lesson').click();
    assert.equal(await page.locator('.lesson-card').count(),data.paths[0].lessonSlugs.length+1);
    assert.equal(await page.locator(`#lesson-option option[value="${extra.slug}"]`).count(),0);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'lesson-option');
    await page.locator(`button[data-slug="${extra.slug}"][data-direction="up"]`).click();
    pass('Search/add duplicate guard and reorder focus');
    const downloadEvent=page.waitForEvent('download');
    await page.locator('#download-session').click();
    const download=await downloadEvent;
    const downloaded=path.join(qa,'session-test-plan.json');
    await download.saveAs(downloaded);
    const plan=JSON.parse(fs.readFileSync(downloaded,'utf8'));
    assert.equal(plan.publicOnly,true);assert.equal(plan.customized,true);assert.equal(plan.audience,'Workshop test group');assert.equal(plan.goal,'Bring back one checked result');assert.equal(plan.sessionMinutes,60);assert.equal(plan.lessons.length,2);
    assert.equal(plan.frameworkAcceptance.status,data.framework.acceptanceStatus);
    assert.equal(plan.frameworkAcceptance.acceptingCommit,data.framework.acceptingCommit);
    for(const lesson of plan.lessons){const current=data.tasks.find(t=>t.slug===lesson.slug);assert.equal(lesson.contentSha256,current.contentSha256);assert.equal(lesson.taskLibraryUrl,current.taskLibraryUrl);}
    assert(plan.reviewWarnings.length>0);
    pass('Actual JSON download selected identities/hashes/current links and customization');
    await page.locator('#present-session').click();
    assert.equal(await page.locator('#presentation').evaluate(e=>e.open),true);
    assert.equal(await page.evaluate(()=>document.activeElement.id),'exit-presentation');
    await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#slide-position').textContent(),'Slide 2 of 4');
    assert((await page.locator('#slide-content').textContent()).includes('not learner acceptance'));
    await page.keyboard.press('ArrowRight');await page.keyboard.press('ArrowRight');
    assert.equal(await page.locator('#next-slide').isDisabled(),true);
    await page.screenshot({path:path.join(qa,'training-presentation-desktop.png')});
    results.screenshots.push('training-presentation-desktop.png');
    await page.keyboard.press('ArrowLeft');assert.equal(await page.locator('#slide-position').textContent(),'Slide 3 of 4');
    await page.keyboard.press('Escape');assert.equal(await page.locator('#presentation').evaluate(e=>e.open),false);assert.equal(await page.evaluate(()=>document.activeElement.id),'present-session');
    pass('Native presentation modal, keyboard/end states, Escape, focus restoration');
    await page.locator('.import-plan summary').click();
    const altered=JSON.parse(JSON.stringify(plan));
    altered.lessons[0].contentSha256='0'.repeat(64);altered.lessons[0].taskLibraryUrl='https://invalid.example/private-course';
    altered.lessons.push({slug:'missing-task-for-qa',title:'Unavailable',contentSha256:'1'.repeat(64),taskLibraryUrl:'https://invalid.example/private-course',article:null,sourceStatus:'complete'});
    altered.exercise={prompt:'Untrusted file exercise',deliverable:'Untrusted',checks:['Untrusted']};
    await page.locator('#import-session').setInputFiles({name:'reopen-test.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(altered))});
    await page.getByText('Saved plan reopened using current public lesson metadata.',{exact:false}).waitFor();
    assert((await page.locator('#source-warning').textContent()).includes('Source changed'));
    assert((await page.locator('#source-warning').textContent()).includes('Missing from this library'));
    assert.equal(await page.locator('#exercise-prompt').textContent(),data.paths[0].exercise.prompt);
    assert.equal(await page.locator('a[href="https://invalid.example/private-course"]').count(),0);
    pass('Saved plan re-resolves sources; changed/missing hash warnings; file exercise/URLs ignored');
    const invalid={...plan,privateInstructorAnswers:'not allowed'};
    await page.locator('#import-session').setInputFiles({name:'invalid-test.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(invalid))});
    await page.getByText('Plan not imported:',{exact:false}).waitFor();
    assert.equal(await page.locator('#session-audience').inputValue(),'Workshop test group');
    pass('Unknown imported fields fail closed, prior plan preserved');
    await page.emulateMedia({media:'print'});
    assert.equal(await page.locator('.print-session-details').isVisible(),true);
    assert.equal(await page.locator('.session-actions').isVisible(),false);
    await page.screenshot({path:path.join(qa,'training-print-full.png'),fullPage:true});results.screenshots.push('training-print-full.png');
    await page.emulateMedia({media:'screen'});
    pass('Print CSS includes adapted summary and selected lessons only');
    await page.setViewportSize({width:390,height:844});
    await page.goto(preview,{waitUntil:'networkidle'});
    await page.screenshot({path:path.join(qa,'training-mobile-390x844.png')});results.screenshots.push('training-mobile-390x844.png');
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.locator('.path-choice').first().click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.screenshot({path:path.join(qa,'training-mobile-path-full.png'),fullPage:true});results.screenshots.push('training-mobile-path-full.png');
    await page.locator('#present-session').click();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true);
    await page.screenshot({path:path.join(qa,'training-presentation-mobile.png')});results.screenshots.push('training-presentation-mobile.png');
    await page.keyboard.press('Escape');
    pass('390px mobile initial/path/modal no horizontal overflow');
    assert.equal(results.outboundRequests.length,0);assert.equal(results.errors.length,0);
    pass('No external requests and no browser page errors');
    await context.close();
  } finally { await browser.close(); }
}
main().then(()=>{results.result='PASS';results.outputDirectory=qa;fs.writeFileSync(path.join(qa,'browser-review.json'),JSON.stringify(results,null,2)+'\n');console.log(JSON.stringify(results,null,2));}).catch(error=>{results.result='FAIL';results.failure=error.stack;fs.writeFileSync(path.join(qa,'browser-review.json'),JSON.stringify(results,null,2)+'\n');console.error(error);process.exitCode=1;});
